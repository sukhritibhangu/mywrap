const { test, before, after } = require('node:test');
const assert = require('node:assert/strict');
const express = require('express');
const bcrypt = require('bcryptjs');
const User = require('../src/models/User');
const { protect, adminOnly } = require('../src/middleware/authMiddleware');
let server, base;
const users = [];
const originalFindOne = User.findOne;
const originalCreate = User.create;
const originalFindById = User.findById;
before(async () => {
  process.env.JWT_SECRET = 'test-only-secret-with-at-least-32-characters';
  User.findOne = query => {
    const user = users.find(u => Object.entries(query).every(([k,v]) => u[k] === v)) || null;
    return { then: resolve => resolve(user), select: async () => user };
  };
  User.create = async data => { const user = { ...data, _id: '507f1f77bcf86cd799439011' }; users.push(user); return user; };
  User.findById = id => ({ select: async () => users.find(u => u._id === id) || null });
  const app = express();
  app.use(express.json());
  app.use('/auth', require('../src/routes/authRoutes'));
  app.get('/protected', protect, (req,res) => res.json({role:req.user.role}));
  app.get('/admin', protect, adminOnly, (req,res) => res.json({success:true}));
  app.use((err,req,res,next) => res.status(500).json({error:err.message}));
  server = await new Promise(resolve => { const s=app.listen(0,'127.0.0.1',()=>resolve(s)); });
  base = `http://127.0.0.1:${server.address().port}`;
});
after(async () => { User.findOne=originalFindOne;User.create=originalCreate;User.findById=originalFindById;await new Promise(resolve=>server.close(resolve)); });
const post = (path,body) => fetch(base+path,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});
test('password signup and login work without OTP, but require a valid password and preserve student permissions', async () => {
  const registration = await post('/auth/register',{name:'Demo Test',email:'test@example.com',phone:'9876543210',password:'Password123',role:'admin'});
  assert.equal(registration.status,201);
  assert.equal((await registration.json()).requiresVerification,undefined);
  assert.equal(users[0].phoneVerified,false);
  assert.equal(users[0].role,'student');
  assert.ok(await bcrypt.compare('Password123',users[0].passwordHash));
  const denied=await post('/auth/login',{email:'test@example.com',password:'wrong'});
  assert.equal(denied.status,401);
  const response=await post('/auth/login',{email:'TEST@example.com',password:'Password123'});
  assert.equal(response.status,200);
  const session=await response.json();
  assert.ok(session.token);
  assert.equal(session.user.passwordHash,undefined);
  const headers={Authorization:`Bearer ${session.token}`};
  assert.equal((await fetch(base+'/protected',{headers})).status,200);
  assert.equal((await fetch(base+'/admin',{headers})).status,403);
  assert.equal((await fetch(base+'/protected')).status,401);
  assert.equal((await post('/auth/otp/send',{phone:'9876543210'})).status,404);
  assert.equal((await post('/auth/otp/verify',{phone:'9876543210',code:'123456'})).status,404);
});
